package io.github.sandeepvijayarao09.anu.brain.gemini

import io.github.sandeepvijayarao09.anu.core.model.BrainEvent
import io.github.sandeepvijayarao09.anu.core.model.BrainRequest
import io.github.sandeepvijayarao09.anu.core.model.ChatMessage
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.addJsonObject
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.intOrNull
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.put
import kotlinx.serialization.json.putJsonArray
import kotlinx.serialization.json.putJsonObject

/**
 * Translates Anu's brain contract to Gemini's `generateContent` JSON and back. Tool and response
 * schemas are passed as JSON Schema (`parametersJsonSchema`, `responseJsonSchema`), so the schemas
 * generated by `core:model` are used unchanged.
 */
internal object GeminiWire {

    fun body(request: BrainRequest): JsonObject = buildJsonObject {
        request.system?.let { system ->
            putJsonObject("systemInstruction") { putJsonArray("parts") { addJsonObject { put("text", system) } } }
        }
        putJsonArray("contents") { request.transcript.forEach { add(content(it)) } }
        if (request.tools.isNotEmpty()) {
            putJsonArray("tools") {
                addJsonObject {
                    putJsonArray("functionDeclarations") {
                        request.tools.forEach { tool ->
                            addJsonObject {
                                put("name", tool.name)
                                put("description", tool.description)
                                put("parametersJsonSchema", tool.parameters)
                            }
                        }
                    }
                }
            }
        }
        putJsonObject("generationConfig") {
            request.maxOutputTokens?.let { put("maxOutputTokens", it) }
            request.responseSchema?.let {
                put("responseMimeType", "application/json")
                put("responseJsonSchema", it)
            }
        }
    }

    fun usage(metadata: JsonObject) = BrainEvent.Usage(
        contextTokens = metadata["totalTokenCount"].int() ?: 0,
        inputTokens = metadata["promptTokenCount"].int(),
        outputTokens = metadata["candidatesTokenCount"].int(),
    )

    private fun content(message: ChatMessage): JsonObject = when (message) {
        is ChatMessage.User -> buildJsonObject {
            put("role", "user")
            putJsonArray("parts") { addJsonObject { put("text", message.text) } }
        }
        is ChatMessage.Model -> buildJsonObject {
            put("role", "model")
            putJsonArray("parts") {
                if (message.text.isNotEmpty() || message.toolCalls.isEmpty()) addJsonObject { put("text", message.text) }
                message.toolCalls.forEach { call ->
                    addJsonObject {
                        putJsonObject("functionCall") {
                            put("name", call.name)
                            put("args", call.arguments)
                        }
                        call.signature?.let { put("thoughtSignature", it) }
                    }
                }
            }
        }
        is ChatMessage.Tool -> buildJsonObject {
            put("role", "user")
            putJsonArray("parts") {
                message.results.forEach { result ->
                    addJsonObject {
                        putJsonObject("functionResponse") {
                            put("name", result.toolName)
                            // Gemini requires an object here. Wrap plain values.
                            put("response", result.result as? JsonObject ?: buildJsonObject { put("result", result.result) })
                        }
                    }
                }
            }
        }
    }

    private fun JsonElement?.int(): Int? = this?.jsonPrimitive?.intOrNull
}
